                    end
                end
            end
        end
    end
end
NeutralMinionDeath = function(C, a4, a5)
    local y, z, A, B, T, U, V, W, X, Y, Z, _, a0, a1, a2
    z = 0
    for U = 1, #NeutralMinionCamps, 1 do
        for Y = 1, #NeutralMinionCamps[U].UniqueNames, 1 do
            for a1 = 1, #NeutralMinionCamps[U].UniqueNames[Y], 1 do
                if NeutralMinionCamps[U].UniqueNames[Y][a1] == C then
                    z = U
                    NeutralMinionCamps[U].AliveTracker[a1] = false
                end
            end
        end
    end
    if 0 < z then
        for U = 1, #NeutralMinionCamps[z].AliveTracker, 1 do
            if NeutralMinionCamps[z].AliveTracker[U] == true then
                y = false
            end
        end
        if y ~= false then
            InitNeutralMinionTimer(
                NeutralMinionCamps[z].Timer,
                NeutralMinionCamps[z].TimerType,
                NeutralMinionCamps[z].GroupsRespawnTime,
                0,
                false
            )
        end
    end
