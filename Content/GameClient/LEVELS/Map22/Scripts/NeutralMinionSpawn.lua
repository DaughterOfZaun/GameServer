SpawnInitialNeutralMinions = function(C)
    local w, x, y, z, A, B, T, U, V, W, X, Y
    if C <= #NeutralMinionCamps then
        x = 0
        y = false
        for T = 1, #NeutralMinionCamps[C].Groups, 1 do
            if 0 < NeutralMinionCamps[C].GroupDelaySpawnTime and y == false then
                NeutralMinionCamps[C].AliveTracker = {}
                for X = 1, #NeutralMinionCamps[C].Groups[T], 1 do
                    NeutralMinionCamps[C].AliveTracker[X] = true
                end
